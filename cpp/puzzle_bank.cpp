static SlitherlinkPuzzle fromEntry(const BankEntry &e) {
    SlitherlinkPuzzle p;
    p.rows = e.rows;
    p.cols = e.cols;
    p.clues.resize(p.rows * p.cols);
    for (int i = 0; i < p.rows * p.cols; ++i) {
        char c = e.cluesStr[i];
        p.clues[i] = (c == '.') ? -1 : (c - '0');
    }
    SlitherlinkGrid g{p.rows, p.cols};
    p.solution.resize(g.numEdges());
    for (int i = 0; i < g.numEdges(); ++i) {
        p.solution[i] = (e.solStr[i] == '1') ? 1 : 0;
    }
    return p;
}

int PuzzleBank::count(const QString &difficultyKey) {
    const QString k = difficultyKey.toLower();
    if (k == QStringLiteral("simple") || k == QStringLiteral("easy")) return sizeof(s_easyBank)/sizeof(s_easyBank[0]);
    if (k == QStringLiteral("medium") || k == QStringLiteral("intermediate")) return sizeof(s_mediumBank)/sizeof(s_mediumBank[0]);
    if (k == QStringLiteral("hard") || k == QStringLiteral("expert")) return sizeof(s_hardBank)/sizeof(s_hardBank[0]);
    return 0;
}

SlitherlinkPuzzle PuzzleBank::getPuzzle(const QString &difficultyKey, int index) {
    const QString k = difficultyKey.toLower();
    if (k == QStringLiteral("simple") || k == QStringLiteral("easy")) {
        int n = sizeof(s_easyBank)/sizeof(s_easyBank[0]);
        int idx = (index >= 0) ? (index % n) : QRandomGenerator::global()->bounded(n);
        return fromEntry(s_easyBank[idx]);
    }
    if (k == QStringLiteral("medium") || k == QStringLiteral("intermediate")) {
        int n = sizeof(s_mediumBank)/sizeof(s_mediumBank[0]);
        int idx = (index >= 0) ? (index % n) : QRandomGenerator::global()->bounded(n);
        return fromEntry(s_mediumBank[idx]);
    }
    if (k == QStringLiteral("hard") || k == QStringLiteral("expert")) {
        int n = sizeof(s_hardBank)/sizeof(s_hardBank[0]);
        int idx = (index >= 0) ? (index % n) : QRandomGenerator::global()->bounded(n);
        return fromEntry(s_hardBank[idx]);
    }
    // For master or dynamic play, generate on the fly
    Difficulty diff = Difficulty::fromKey(difficultyKey);
    return SlitherlinkEngine::generatePuzzle(diff);
}
